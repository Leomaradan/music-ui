import { z } from 'zod';

/**
 * Dynamic ("smart") playlists (PLAN.md §7.2b): saved criteria over track tags. Stored by the app,
 * not in Navidrome, and evaluated in the browser against the catalog, so they follow every
 * library sync.
 */

/** Tags a criterion can test. `artist` is the album artist, like the Artist filter. */
export const DYNAMIC_FIELDS = [
  'genre',
  'artist',
  'trackArtist',
  'album',
  'year',
  'folder',
  'format',
] as const;
export type DynamicField = (typeof DYNAMIC_FIELDS)[number];

export const FIELD_LABELS: Record<DynamicField, string> = {
  genre: 'Genre',
  artist: 'Artist',
  trackArtist: 'Track artist',
  album: 'Album',
  year: 'Year',
  folder: 'Music folder',
  format: 'Format',
};

export const DYNAMIC_OPERATORS = ['==', '!=', '<', '<=', '>', '>='] as const;
export type DynamicOperator = (typeof DYNAMIC_OPERATORS)[number];

/** Numeric fields accept ordering operators; the others only `==` and `!=`. */
export const NUMERIC_FIELDS: ReadonlySet<DynamicField> = new Set(['year']);

export const operatorsFor = (field: DynamicField): readonly DynamicOperator[] =>
  NUMERIC_FIELDS.has(field) ? DYNAMIC_OPERATORS : ['==', '!='];

export const OPERATOR_LABELS: Record<DynamicOperator, string> = {
  '==': 'is',
  '!=': 'is not',
  '<': 'before',
  '<=': 'up to',
  '>': 'after',
  '>=': 'from',
};

const criterionSchema = z
  .object({
    field: z.enum(DYNAMIC_FIELDS),
    op: z.enum(DYNAMIC_OPERATORS),
    value: z.union([z.string().max(500), z.number().int().min(0).max(9999)]),
  })
  .refine((c) => operatorsFor(c.field).includes(c.op), {
    message: 'This operator needs a numeric field (year)',
    path: ['op'],
  })
  .refine((c) => NUMERIC_FIELDS.has(c.field) === (typeof c.value === 'number'), {
    message: 'The year needs a number, other fields a text',
    path: ['value'],
  });

/** What the editor sends: everything but the id. */
export const dynamicPlaylistInputSchema = z.object({
  name: z.string().trim().min(1).max(200),
  match: z.enum(['all', 'any']),
  criteria: z.array(criterionSchema).min(1).max(50),
});

export type DynamicCriterion = z.infer<typeof criterionSchema>;
export type DynamicPlaylistInput = z.infer<typeof dynamicPlaylistInputSchema>;
export interface DynamicPlaylist extends DynamicPlaylistInput {
  id: string;
}

/** Ids are generated by the server: `d` followed by hex digits. */
export const dynamicPlaylistIdSchema = z.string().regex(/^d[0-9a-f]{1,32}$/);
